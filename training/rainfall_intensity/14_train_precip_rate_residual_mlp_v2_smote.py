def evaluate_loss(model, loader):

    model.eval()

    total_loss = 0.0
    total_reg = 0.0
    total_cls = 0.0
    total_samples = 0

    with torch.no_grad():

        for X_batch, y_batch, class_batch in loader:

            X_batch = X_batch.to(
                DEVICE,
                non_blocking=True
            )

            y_batch = y_batch.to(
                DEVICE,
                non_blocking=True
            )

            class_batch = class_batch.to(
                DEVICE,
                non_blocking=True
            )

            pred, class_logits = model(X_batch)

            reg_loss = weighted_huber_loss(
                pred,
                y_batch,
                class_batch
            )

            cls_loss = classification_loss_fn(
                class_logits,
                class_batch
            )

            loss = (
                reg_loss
                + CLASSIFICATION_WEIGHT * cls_loss
            )

            batch_size = len(X_batch)

            total_loss += loss.item() * batch_size
            total_reg += reg_loss.item() * batch_size
            total_cls += cls_loss.item() * batch_size

            total_samples += batch_size

    return (
        total_loss / total_samples,
        total_reg / total_samples,
        total_cls / total_samples,
    )

