def smote_regression_class(
    X,
    y_log,
    classes,
    class_id,
    target_count,
    k_neighbors=5,
    random_state=42,
):
    """
    Generate synthetic samples for one intensity class.

    Feature vectors:
        x_new = x_i + lambda * (x_neighbor - x_i)

    Target:
        log_target_new =
            log_y_i + lambda * (log_y_neighbor - log_y_i)

    Thus both predictors and precipitation rate remain internally
    consistent with the interpolation.

    IMPORTANT:
        This operates only on training samples.
    """

    rng = np.random.default_rng(random_state)

    idx = np.where(classes == class_id)[0]

    current_count = len(idx)

    if target_count <= current_count:
        return (
            np.empty((0, X.shape[1]), dtype=np.float32),
            np.empty((0,), dtype=np.float32),
        )

    n_synthetic = target_count - current_count

    X_class = X[idx]
    y_class = y_log[idx]

    if current_count <= 1:
        raise ValueError(
            f"Class {class_id} has too few samples for SMOTE."
        )

    k = min(k_neighbors, current_count - 1)

    print()
    print(
        f"Class {class_id} ({class_names[class_id]}): "
        f"{current_count:,} -> {target_count:,}"
    )
    print(f"Synthetic samples: {n_synthetic:,}")
    print(f"k-neighbors     : {k}")

    # ----------------------------------------------------------------------
    # Compute nearest neighbours.
    #
    # Using numpy distance calculation in chunks avoids constructing a huge
    # N x N matrix for the full training set.
    # ----------------------------------------------------------------------

    from sklearn.neighbors import NearestNeighbors

    nn_model = NearestNeighbors(
        n_neighbors=k + 1,
        metric="euclidean",
        n_jobs=-1,
    )

    nn_model.fit(X_class)

    # Generate source indices.
    source_local = rng.integers(
        low=0,
        high=current_count,
        size=n_synthetic,
    )

    # We need nearest-neighbour candidates for the selected sources.
    selected_X = X_class[source_local]

    _, neighbor_indices = nn_model.kneighbors(selected_X)

    # First neighbour is the point itself.
    neighbor_choice = rng.integers(
        low=1,
        high=k + 1,
        size=n_synthetic,
    )

    neighbor_local = neighbor_indices[
        np.arange(n_synthetic),
        neighbor_choice,
    ]

    x1 = X_class[source_local]
    x2 = X_class[neighbor_local]

    y1 = y_class[source_local]
    y2 = y_class[neighbor_local]

    lam = rng.random(n_synthetic).astype(np.float32)

    lam_x = lam[:, None]

    X_synthetic = (
        x1 + lam_x * (x2 - x1)
    ).astype(np.float32)

    y_synthetic = (
        y1 + lam * (y2 - y1)
    ).astype(np.float32)

    return X_synthetic, y_synthetic


